import asyncio
import logging
import os
from datetime import datetime, timezone
from pathlib import Path
from tempfile import TemporaryDirectory

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import text
from sqlalchemy.engine import make_url
from starlette.responses import FileResponse

from app.auth.infrastructure.dependencies import require_system_admin
from app.core.config import settings
from app.core.database import AsyncSessionLocal

logger = logging.getLogger("magnus.backup")
router = APIRouter(prefix="/auth/database-backup", tags=["Database Backup"])
BACKUP_LOCK_ID = 746192035
BACKUP_TIMEOUT_SECONDS = 300


class BackupDownload(FileResponse):
    def __init__(self, path: Path, directory: TemporaryDirectory, filename: str):
        super().__init__(
            path,
            filename=filename,
            media_type="application/octet-stream",
            headers={"Cache-Control": "no-store", "X-Content-Type-Options": "nosniff"},
        )
        self.directory = directory

    async def __call__(self, scope, receive, send):
        try:
            await super().__call__(scope, receive, send)
        finally:
            self.directory.cleanup()


async def create_database_dump(path: Path) -> None:
    url = make_url(settings.DATABASE_URL)
    if url.get_backend_name() != "postgresql" or not url.database or not url.username:
        logger.error("Database backup requires a configured PostgreSQL connection.")
        raise HTTPException(503, "Database backup is not configured. Contact the system administrator.")
    env = os.environ.copy()
    env.update({
        "PGHOST": url.host or settings.DB_HOST,
        "PGPORT": str(url.port or settings.DB_PORT),
        "PGDATABASE": url.database,
        "PGUSER": url.username,
        "PGPASSWORD": url.password or "",
        "PGCONNECT_TIMEOUT": "15",
    })
    if url.query.get("sslmode"):
        env["PGSSLMODE"] = str(url.query["sslmode"])
    process = None
    try:
        process = await asyncio.create_subprocess_exec(
            "pg_dump", "--format=custom", "--no-password", "--lock-wait-timeout=15000",
            "--file", str(path),
            env=env, stdout=asyncio.subprocess.DEVNULL, stderr=asyncio.subprocess.DEVNULL,
        )
        await asyncio.wait_for(process.wait(), timeout=BACKUP_TIMEOUT_SECONDS)
    except FileNotFoundError as error:
        logger.error("Database backup failed: pg_dump is not installed.")
        raise HTTPException(503, "PostgreSQL backup tools are not installed. Contact the system administrator.") from error
    except asyncio.TimeoutError as error:
        logger.error("Database backup exceeded its time limit.")
        raise HTTPException(504, "Backup exceeded five minutes. Ask the administrator to use an operational backup job.") from error
    except OSError as error:
        logger.error("Database backup failed with operating system error %s.", error.errno)
        raise HTTPException(500, "The database backup could not be created. Check server storage and configuration.") from error
    finally:
        if process is not None and process.returncode is None:
            process.kill()
            await process.wait()
    if process.returncode != 0:
        logger.error("pg_dump failed with exit code %s.", process.returncode)
        raise HTTPException(500, "The database backup failed. Check PostgreSQL connectivity, client version, permissions, and server storage.")
    with path.open("rb") as archive:
        if archive.read(5) != b"PGDMP":
            logger.error("Database backup did not produce a PostgreSQL archive.")
            raise HTTPException(500, "The database backup archive is invalid. No download was created.")


@router.post("")
async def download_database_backup(claims: dict = Depends(require_system_admin)):
    directory = TemporaryDirectory(prefix="magnus-backup-")
    transferred = False
    try:
        async with AsyncSessionLocal() as session:
            async with session.begin():
                acquired = await session.scalar(
                    text("SELECT pg_try_advisory_xact_lock(:key)"), {"key": BACKUP_LOCK_ID},
                )
                if not acquired:
                    raise HTTPException(409, "Another database backup is being created. Please try again after it finishes.")
                path = Path(directory.name) / "database.dump"
                await create_database_dump(path)
        filename = f"magnus-database-{datetime.now(timezone.utc):%Y%m%dT%H%M%SZ}.dump"
        logger.info("Database backup generated by user %s.", claims["sub"])
        response = BackupDownload(path, directory, filename)
        transferred = True
        return response
    finally:
        if not transferred:
            directory.cleanup()
